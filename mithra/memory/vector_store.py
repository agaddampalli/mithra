"""
VectorStore — ChromaDB wrapper for semantic memory.

One collection per domain. Embeddings are generated by the LiteLLM proxy
(http://llm-router:4000/v1/embeddings) so no local embedding model is needed.

ChromaDB runs as a Docker container on port 8001.
Inject client=chromadb.EphemeralClient() in unit tests to avoid network calls.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

import requests

import chromadb

_EMBED_URL = "http://llm-router:4000/v1/embeddings"
_EMBED_MODEL = "text-embedding-ada-002"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


class VectorStore:
    """ChromaDB-backed semantic memory store with LiteLLM-generated embeddings."""

    def __init__(
        self,
        host: str = "vector-store",
        port: int = 8001,
        client: Any = None,
    ) -> None:
        """
        Args:
            host: ChromaDB host (Docker service name or IP).
            port: ChromaDB HTTP port.
            client: Injectable ChromaDB client for tests (e.g. EphemeralClient).
                    When None, connects to http://host:port via HttpClient.
        """
        self.host = host
        self.port = port
        if client is not None:
            self._client = client
        else:
            self._client = chromadb.HttpClient(host=host, port=port)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _get_embedding(self, text: str) -> list[float]:
        """Call LiteLLM proxy to generate an embedding for text."""
        resp = requests.post(
            _EMBED_URL,
            json={"model": _EMBED_MODEL, "input": text},
            timeout=10,
        )
        resp.raise_for_status()
        return resp.json()["data"][0]["embedding"]

    def _collection(self, domain: str):
        """Return (or create) the ChromaDB collection for a domain."""
        return self._client.get_or_create_collection(
            name=domain,
            metadata={"hnsw:space": "cosine"},
        )

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def write(
        self,
        domain: str,
        key: str,
        text: str,
        metadata: dict[str, Any] | None = None,
    ) -> None:
        """Embed text and upsert into the domain collection.

        metadata always contains: key, domain, indexed_at.
        Any caller-supplied keys are merged in (caller keys take lower priority).
        """
        col = self._collection(domain)
        embedding = self._get_embedding(text)
        meta = dict(metadata or {})
        meta.update({"key": key, "domain": domain, "indexed_at": _now()})
        col.upsert(
            ids=[key],
            documents=[text],
            embeddings=[embedding],
            metadatas=[meta],
        )

    def search(
        self,
        domain: str,
        query: str,
        top_k: int = 5,
    ) -> list[dict[str, Any]]:
        """Return top_k semantically similar documents from the domain collection.

        Returns [] if the collection does not exist yet.
        Each result: {key, text, score, metadata}.
        score = 1 - cosine_distance (higher is more similar).
        """
        try:
            col = self._client.get_collection(name=domain)
        except Exception:
            return []

        count = col.count()
        if count == 0:
            return []

        embedding = self._get_embedding(query)
        results = col.query(
            query_embeddings=[embedding],
            n_results=min(top_k, count),
        )

        out: list[dict[str, Any]] = []
        ids = results.get("ids", [[]])[0]
        docs = results.get("documents", [[]])[0]
        dists = results.get("distances", [[0.0] * len(ids)])[0]
        metas = results.get("metadatas", [[{}] * len(ids)])[0]

        for i, doc_id in enumerate(ids):
            out.append({
                "key": doc_id,
                "text": docs[i],
                "score": 1.0 - dists[i],
                "metadata": metas[i],
            })
        return out

    def delete(self, domain: str, key: str) -> None:
        """Remove a document by key. No-op if collection or key does not exist."""
        try:
            col = self._client.get_collection(name=domain)
            col.delete(ids=[key])
        except Exception:
            pass

    def health(self) -> dict[str, Any]:
        """Return ChromaDB reachability status."""
        try:
            cols = self._client.list_collections()
            return {"status": "ok", "collection_count": len(cols), "error": None}
        except Exception as exc:
            return {"status": "error", "collection_count": 0, "error": str(exc)}
