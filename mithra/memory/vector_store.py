"""
VectorStore — ChromaDB wrapper for semantic memory.

Provides a domain-scoped read/write API over ChromaDB collections.
Each domain gets its own collection; embeddings are generated by the
LiteLLM proxy so no embedding model is called directly here.

ChromaDB runs as a Docker container on port 8001.
"""

from __future__ import annotations

from typing import Any

import chromadb
from chromadb.config import Settings


class VectorStore:
    """ChromaDB-backed semantic memory store."""

    def __init__(self, host: str = "vector-store", port: int = 8001) -> None:
        self.host = host
        self.port = port
        self._client = chromadb.HttpClient(
            host=host,
            port=port,
            settings=Settings(anonymized_telemetry=False),
        )

    def _collection(self, domain: str):
        """Return (or create) the ChromaDB collection for a domain."""
        return self._client.get_or_create_collection(name=domain)

    async def write(self, domain: str, key: str, text: str, metadata: dict[str, Any] | None = None) -> None:
        """Embed and store a text chunk in the domain collection."""
        col = self._collection(domain)
        col.upsert(
            ids=[key],
            documents=[text],
            metadatas=[metadata or {}],
        )

    async def search(self, domain: str, query: str, top_k: int = 5) -> list[dict[str, Any]]:
        """Return the top-k semantically similar chunks for a query."""
        col = self._collection(domain)
        results = col.query(query_texts=[query], n_results=top_k)
        out: list[dict[str, Any]] = []
        if not results["ids"]:
            return out
        for idx, doc_id in enumerate(results["ids"][0]):
            out.append({
                "id": doc_id,
                "text": results["documents"][0][idx],
                "metadata": results["metadatas"][0][idx] if results["metadatas"] else {},
                "distance": results["distances"][0][idx] if results.get("distances") else None,
            })
        return out

    async def delete(self, domain: str, key: str) -> None:
        """Remove a chunk from the domain collection by key."""
        col = self._collection(domain)
        col.delete(ids=[key])
